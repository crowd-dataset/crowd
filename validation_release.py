def sha256_file(path: Path, chunk_size: int = 1024 * 1024) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        while True:
            b = f.read(chunk_size)
            if not b:
                break
            h.update(b)
    return h.hexdigest()


def count_csv_data_rows(path: Path) -> Optional[int]:
    """Return number of data rows in a CSV (excluding header). None if unreadable."""
    try:
        with path.open("r", encoding="utf-8", errors="replace") as f:
            n_lines = sum(1 for _ in f)
        return max(int(n_lines) - 1, 0)
    except Exception:
        return None


def _num_from_str(s: str) -> Optional[float]:
    if s is None:
        return None
    ss = str(s).strip().replace(",", "")
    if ss.endswith("%"):
        ss = ss[:-1].strip()
    if ss == "":
        return None
    try:
        return float(ss)
    except Exception:
        return None


def _int_from_any(v: Any) -> Optional[int]:
    if v is None:
        return None
    if isinstance(v, bool):
        return int(v)
    if isinstance(v, int):
        return v
    try:
        return int(v)
    except Exception:
        try:
            f = float(str(v).strip())
            if math.isfinite(f):
                return int(f)
        except Exception:
            return None
    return None


def safe_eval_list(x: Any) -> List[Any]:
    """Parse list-like cell robustly."""
    if x is None:
        return []
    if isinstance(x, list):
        return x
    if not isinstance(x, str):
        return []

    s = x.strip()
    if s == "" or s.lower() in {"nan", "none", "null"}:
        return []

    # strip wrapping quotes if the entire cell is quoted
    if (len(s) >= 2) and ((s[0] == s[-1]) and s[0] in {"'", '"'}):
        s = s[1:-1].strip()

    if s == "" or s == "[]":
        return []

    try:
        v = ast.literal_eval(s)
        return v if isinstance(v, list) else []
    except Exception:
        # Fallback: [a,b,c] with bare tokens
        if s.startswith("[") and s.endswith("]"):
            inner = s[1:-1].strip()
            if inner == "":
                return []
            parts = [p.strip().strip('"').strip("'") for p in inner.split(",")]
            return [p for p in parts if p != ""]
        return []


