def _valid_upload_ymd(year: int, month: int, day: int) -> Optional[Tuple[int, int, int]]:
    """Return a validated (year, month, day), otherwise None."""
    if year < 1900 or year > 2100 or month < 1 or month > 12:
        return None

    days_in_month = {
        1: 31,
        2: 29 if ((year % 4 == 0 and year % 100 != 0) or (year % 400 == 0)) else 28,
        3: 31,
        4: 30,
        5: 31,
        6: 30,
        7: 31,
        8: 31,
        9: 30,
        10: 31,
        11: 30,
        12: 31,
    }
    if day < 1 or day > days_in_month[month]:
        return None

    return year, month, day


def _normalise_upload_date(raw: Any) -> Optional[Tuple[int, int, int]]:
    """Return (year, month, day) for upload dates from mapping.csv or metadata.

    Supported forms include:
      - YYYY-MM-DD / YYYY/MM/DD
      - YYYYMMDD
      - compact mapping.csv values such as 29082023, 3042024, 9122023
        interpreted as DDMMYYYY or DMMYYYY.
    """
    if raw is None:
        return None

    s = str(raw).strip()
    if not s or s.lower() in {"nan", "none", "null", "na", "n/a", "unknown", "unavailable", "#n/a"}:
        return None

    # Preferred form from YouTube metadata: YYYY-MM-DD, with / also accepted.
    m = re.search(r"(?P<year>20\d{2}|19\d{2})[-/](?P<month>0?[1-9]|1[0-2])[-/](?P<day>0?[1-9]|[12]\d|3[01])", s)
    if m:
        return _valid_upload_ymd(int(m.group("year")), int(m.group("month")), int(m.group("day")))

    # Metadata fallback: compact YYYYMMDD strings.
    m = re.search(r"(?P<year>20\d{2}|19\d{2})(?P<month>0[1-9]|1[0-2])(?P<day>0[1-9]|[12]\d|3[01])", s)
    if m:
        return _valid_upload_ymd(int(m.group("year")), int(m.group("month")), int(m.group("day")))

    # mapping.csv stores many upload dates as compact DDMMYYYY / DMMYYYY values.
    # Examples: 29082023 -> 2023-08-29, 3042024 -> 2024-04-03, 9122023 -> 2023-12-09.
    digits = re.sub(r"\D", "", s)
    if 5 <= len(digits) <= 8:
        year_text = digits[-4:]
        day_month_text = digits[:-4]
        try:
            year = int(year_text)
        except Exception:
            return None

        split_candidates: List[Tuple[str, str]] = []
        if len(day_month_text) >= 3:
            # Prefer a two-digit month, matching the mapping.csv compact format.
            split_candidates.append((day_month_text[:-2], day_month_text[-2:]))
        if len(day_month_text) >= 2:
            # Fallback for rare DMY / DDMYYYY-like compact values.
            split_candidates.append((day_month_text[:-1], day_month_text[-1:]))

        for day_text, month_text in split_candidates:
            if not day_text or not month_text:
                continue
            try:
                parsed = _valid_upload_ymd(year, int(month_text), int(day_text))
            except Exception:
                parsed = None
            if parsed is not None:
                return parsed

    return None


def _quarter_from_month(month: int) -> int:
    return ((int(month) - 1) // 3) + 1


def summarise_upload_date_distribution(
    video_aggs: Dict[str, VideoAgg],
    out_dir: Path,
    logger: logging.Logger,
    report: Report,
) -> Dict[str, Any]:
    """Export upload-date counts needed for Figure 2 and its caption.

    Upload dates are read from mapping.csv through ``VideoAgg.upload_dates``.
    Counts are over unique videos that appear in mapping.csv, not over
    metadata-only rows.
    """
    year_counts: Counter[int] = Counter()
    quarter_counts: Counter[Tuple[int, int]] = Counter()
    missing_examples: List[Dict[str, Any]] = []

    valid_dates = 0
    omitted_unavailable = 0
    min_date: Optional[Tuple[int, int, int]] = None
    max_date: Optional[Tuple[int, int, int]] = None

    conflicting_date_examples: List[Dict[str, Any]] = []
    videos_with_conflicting_valid_dates = 0

    for vid in sorted(video_aggs.keys()):
        raw_dates = [str(v).strip() for v in video_aggs[vid].upload_dates if str(v).strip()]
        parsed_dates: List[Tuple[Tuple[int, int, int], str]] = []

        for raw_date in raw_dates:
            parsed = _normalise_upload_date(raw_date)
            if parsed is not None:
                parsed_dates.append((parsed, raw_date))

        if not parsed_dates:
            omitted_unavailable += 1
            if len(missing_examples) < 25:
                missing_examples.append(
                    {
                        "video": vid,
                        "raw_upload_dates": raw_dates,
                        "reason": "missing_or_unparseable_upload_date_in_mapping_csv",
                    }
                )
            continue

        unique_valid_dates = sorted({p for p, _ in parsed_dates})
        if len(unique_valid_dates) > 1:
            videos_with_conflicting_valid_dates += 1
            if len(conflicting_date_examples) < 25:
                conflicting_date_examples.append(
                    {
                        "video": vid,
                        "raw_upload_dates": raw_dates,
                        "valid_dates": [f"{d[0]:04d}-{d[1]:02d}-{d[2]:02d}" for d in unique_valid_dates],
                    }
                )

        # Use the first valid mapping.csv upload date for the unique-video distribution.
        # The conflict count above flags the rare cases where the same video has more than one valid date.
        parsed = parsed_dates[0][0]
        year, month, day = parsed
        quarter = _quarter_from_month(month)
        year_counts[year] += 1
        quarter_counts[(year, quarter)] += 1
        valid_dates += 1

        if min_date is None or parsed < min_date:
            min_date = parsed
        if max_date is None or parsed > max_date:
            max_date = parsed

    year_csv_path = out_dir / "upload_date_distribution_by_year.csv"
    quarter_csv_path = out_dir / "upload_date_distribution_by_quarter.csv"
    summary_json_path = out_dir / "upload_date_figure_summary.json"

    with year_csv_path.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["year", "videos", "incomplete_period"])
        w.writeheader()
        for year in sorted(year_counts.keys()):
            w.writerow(
                {
                    "year": year,
                    "videos": int(year_counts[year]),
                    "incomplete_period": bool(year == 2026 and year_counts[year] > 0),
                }
            )

    with quarter_csv_path.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["year", "quarter", "period", "videos", "incomplete_period"])
        w.writeheader()
        for year, quarter in sorted(quarter_counts.keys()):
            w.writerow(
                {
                    "year": year,
                    "quarter": quarter,
                    "period": f"{year}-Q{quarter}",
                    "videos": int(quarter_counts[(year, quarter)]),
                    "incomplete_period": bool(year == 2026),
                }
            )

    max_date_text = None if max_date is None else f"{max_date[0]:04d}-{max_date[1]:02d}-{max_date[2]:02d}"
    min_date_text = None if min_date is None else f"{min_date[0]:04d}-{min_date[1]:02d}-{min_date[2]:02d}"
    videos_2026 = int(year_counts.get(2026, 0))
    year_2026_incomplete = videos_2026 > 0

    summary = {
        "unique_videos_in_mapping": int(len(video_aggs)),
        "valid_upload_dates": int(valid_dates),
        "omitted_unavailable_upload_dates": int(omitted_unavailable),
        "first_valid_upload_date": min_date_text,
        "latest_valid_upload_date": max_date_text,
        "videos_with_2026_upload_dates": videos_2026,
        "year_2026_incomplete": bool(year_2026_incomplete),
        "caption_note": (
            f"The 2026 period is incomplete; {videos_2026:,} videos with 2026 upload dates are shown. "
            f"Videos omitted because upload dates were unavailable: {omitted_unavailable:,}."
        ),
        "year_distribution_csv": str(year_csv_path),
        "quarter_distribution_csv": str(quarter_csv_path),
        "missing_examples": missing_examples,
        "videos_with_conflicting_valid_mapping_upload_dates": int(videos_with_conflicting_valid_dates),
        "conflicting_valid_mapping_upload_date_examples": conflicting_date_examples,
    }

    summary_json_path.write_text(json.dumps(summary, indent=2), encoding="utf-8")

    report.add(
        "upload_dates.figure_metadata",
        ok=True,
        details={k: v for k, v in summary.items() if k != "missing_examples"} | {"missing_examples": missing_examples},
    )

    logger.info("\n=== Figure 2 upload-date metadata ===")
    logger.info(f"Videos with valid upload dates included in distribution: {fmt_int(valid_dates)}")
    logger.info(f"Videos omitted because upload dates were unavailable: {fmt_int(omitted_unavailable)}")
    logger.info(
        "Videos with conflicting valid mapping.csv upload dates: "
        f"{fmt_int(videos_with_conflicting_valid_dates)}"
    )
    logger.info(f"2026 incomplete period: {year_2026_incomplete}; videos in 2026: {fmt_int(videos_2026)}")
    logger.info(f"Upload-date year distribution CSV: {year_csv_path}")
    logger.info(f"Upload-date quarter distribution CSV: {quarter_csv_path}")
    logger.info(f"Upload-date figure summary JSON: {summary_json_path}")

    return summary


def export_validation_video_issues_csv(
    out_csv_path: Path,
    multi_continent_videos: Sequence[str],
    metadata_duplicate_counts: Dict[str, int],
    missing_metadata_videos: Sequence[str],
    missing_in_mapping_videos: Sequence[str],
    logger: logging.Logger,
) -> None:
    """Write a single CSV containing videos involved in selected checks."""
    out_csv_path.parent.mkdir(parents=True, exist_ok=True)

    with out_csv_path.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(
            f,
            fieldnames=[
                "category",
                "video",
                "reason",
            ],
        )
        w.writeheader()

        # 1) mapping_csv.multi_continent_videos
        for vid in sorted(set(multi_continent_videos)):
            w.writerow(
                {
                    "category": "mapping_csv.multi_continent_videos",
                    "video": vid,
                    "reason": "multiple_continents",
                }
            )

        # 2) mapping_metadata.duplicate_video_rows
        for vid in sorted(metadata_duplicate_counts.keys()):
            w.writerow(
                {
                    "category": "mapping_metadata.duplicate_video_rows",
                    "video": vid,
                    "reason": f"duplicate_rows:{int(metadata_duplicate_counts.get(vid, 0))}",
                }
            )

        # 3) mapping_vs_metadata.missing_metadata_rows
        for vid in sorted(set(missing_metadata_videos)):
            w.writerow(
                {
                    "category": "mapping_vs_metadata.missing_metadata_rows",
                    "video": vid,
                    "reason": "missing_metadata",
                }
            )

        # 4) metadata_vs_mapping.missing_in_mapping
        for vid in sorted(set(missing_in_mapping_videos)):
            w.writerow(
                {
                    "category": "metadata_vs_mapping.missing_in_mapping",
                    "video": vid,
                    "reason": "missing_in_mapping",
                }
            )

    logger.info(f"Validation video issues CSV written: {out_csv_path}")

def _json_get(obj: Dict[str, Any], path: Sequence[str]) -> Any:
    cur: Any = obj
    for part in path:
        if not isinstance(cur, dict) or part not in cur:
            return None
        cur = cur[part]
    return cur


def _float_close(a: Any, b: Any, tol: float = 1e-6) -> bool:
    try:
        af = float(a)
        bf = float(b)
        return math.isfinite(af) and math.isfinite(bf) and abs(af - bf) <= tol
    except Exception:
        return False


def validate_crowd_index_jsonl(
    jsonl_path: Path,
    mapping_path: Path,
    logger: logging.Logger,
    report: Report,
) -> Dict[str, Any]:
    """Validate that crowd_index.jsonl is valid, complete, and current."""
    records, read_summary = _jsonl_read_existing(jsonl_path, report)
    expected = _jsonl_expected_records_from_mapping(mapping_path, logger, report)

    expected_ids = set(expected.keys())
    observed_ids = set(records.keys())
    missing_ids = sorted(expected_ids - observed_ids)
    extra_ids = sorted(observed_ids - expected_ids)

    report.add(
        "crowd_index_jsonl.complete_vs_mapping",
        ok=(len(missing_ids) == 0 and len(extra_ids) == 0 and len(records) == len(expected)),
        details={
            "expected_records_from_mapping": len(expected),
            "jsonl_unique_records": len(records),
            "missing_record_count": len(missing_ids),
            "extra_record_count": len(extra_ids),
            "missing_examples": missing_ids[:25],
            "extra_examples": extra_ids[:25],
        },
        warn=False,
    )

    required_top = {"record_type", "schema_version", "segment_id", "video_id", "source", "upload", "segment", "labels", "location", "automatic_outputs"}
    required_nested = [
        ("source", "platform"),
        ("source", "watch_url"),
        ("source", "underlying_video_redistributed"),
        ("upload", "upload_date"),
        ("upload", "recording_date"),
        ("upload", "recording_date_provenance"),
        ("upload", "recording_date_uncertainty"),
        ("segment", "start_time_s"),
        ("segment", "end_time_s"),
        ("segment", "processed_end_time_s"),
        ("segment", "endpoint_adjustment_s"),
        ("segment", "processed_duration_s"),
        ("labels", "time_of_day_code"),
        ("labels", "vehicle_type_code"),
        ("automatic_outputs", "bbox_csv_expected_prefix"),
        ("automatic_outputs", "object_level_ground_truth"),
    ]

    missing_required_examples: List[Dict[str, Any]] = []
    bad_value_examples: List[Dict[str, Any]] = []
    mismatch_examples: List[Dict[str, Any]] = []
    source_free_text_examples: List[Dict[str, Any]] = []
    free_text_keys = {"title", "description", "channel", "chapters", "tags", "categories"}

    n_missing_required = 0
    n_bad_governance_values = 0
    n_value_mismatches = 0
    n_source_free_text = 0

    for segment_id in sorted(observed_ids):
        obj = records[segment_id]

        missing_for_record = [k for k in sorted(required_top) if k not in obj]
        for path in required_nested:
            if _json_get(obj, path) is None and path not in {("upload", "recording_date"), ("upload", "recording_date_provenance")}:
                missing_for_record.append(".".join(path))
            elif path in {("upload", "recording_date"), ("upload", "recording_date_provenance")}:
                # These fields must exist and be null, so distinguish missing from null.
                parent = obj.get(path[0])
                if not isinstance(parent, dict) or path[1] not in parent:
                    missing_for_record.append(".".join(path))

        if missing_for_record:
            n_missing_required += 1
            if len(missing_required_examples) < 25:
                missing_required_examples.append({"segment_id": segment_id, "missing": missing_for_record[:20]})

        # Governance/privacy/ground-truth values should remain explicit.
        if _json_get(obj, ("source", "underlying_video_redistributed")) is not False:
            n_bad_governance_values += 1
            if len(bad_value_examples) < 25:
                bad_value_examples.append({"segment_id": segment_id, "field": "source.underlying_video_redistributed"})
        if _json_get(obj, ("automatic_outputs", "object_level_ground_truth")) is not False:
            n_bad_governance_values += 1
            if len(bad_value_examples) < 25:
                bad_value_examples.append({"segment_id": segment_id, "field": "automatic_outputs.object_level_ground_truth"})
        if _json_get(obj, ("upload", "recording_date")) is not None:
            n_bad_governance_values += 1
            if len(bad_value_examples) < 25:
                bad_value_examples.append({"segment_id": segment_id, "field": "upload.recording_date"})
        if _json_get(obj, ("upload", "recording_date_uncertainty")) != "not_available":
            n_bad_governance_values += 1
            if len(bad_value_examples) < 25:
                bad_value_examples.append({"segment_id": segment_id, "field": "upload.recording_date_uncertainty"})

        upload_metadata = obj.get("upload_metadata")
        if isinstance(upload_metadata, dict):
            leaked = sorted(k for k in upload_metadata.keys() if str(k).lower() in free_text_keys)
            if leaked:
                n_source_free_text += 1
                if len(source_free_text_examples) < 25:
                    source_free_text_examples.append({"segment_id": segment_id, "keys": leaked})

        exp = expected.get(segment_id)
        if exp is None:
            continue

        if obj.get("video_id") != exp["video_id"]:
            n_value_mismatches += 1
            if len(mismatch_examples) < 25:
                mismatch_examples.append(
                    {"segment_id": segment_id, "field": "video_id", "jsonl": obj.get("video_id"), "expected": exp["video_id"]}
                )
        if not _float_close(_json_get(obj, ("segment", "start_time_s")), exp["start_time_s"]):
            n_value_mismatches += 1
            if len(mismatch_examples) < 25:
                mismatch_examples.append(
                    {"segment_id": segment_id, "field": "segment.start_time_s", "jsonl": _json_get(obj, ("segment", "start_time_s")), "expected": exp["start_time_s"]}
                )
        if not _float_close(_json_get(obj, ("segment", "end_time_s")), exp["end_time_s"]):
            n_value_mismatches += 1
            if len(mismatch_examples) < 25:
                mismatch_examples.append(
                    {"segment_id": segment_id, "field": "segment.end_time_s", "jsonl": _json_get(obj, ("segment", "end_time_s")), "expected": exp["end_time_s"]}
                )
        if not _float_close(_json_get(obj, ("segment", "processed_duration_s")), exp["processed_duration_s"]):
            n_value_mismatches += 1
            if len(mismatch_examples) < 25:
                mismatch_examples.append(
                    {"segment_id": segment_id, "field": "segment.processed_duration_s", "jsonl": _json_get(obj, ("segment", "processed_duration_s")), "expected": exp["processed_duration_s"]}
                )

    report.add(
        "crowd_index_jsonl.required_schema_fields",
        ok=(n_missing_required == 0),
        details={"records_with_missing_required_fields": n_missing_required, "examples": missing_required_examples},
        warn=False,
    )
    report.add(
        "crowd_index_jsonl.values_match_mapping",
        ok=(n_value_mismatches == 0),
        details={"mismatch_count": n_value_mismatches, "examples": mismatch_examples},
        warn=False,
    )
    report.add(
        "crowd_index_jsonl.governance_flags",
        ok=(n_bad_governance_values == 0),
        details={"bad_value_count": n_bad_governance_values, "examples": bad_value_examples},
        warn=False,
    )
    report.add(
        "crowd_index_jsonl.no_source_free_text_metadata",
        ok=(n_source_free_text == 0),
        details={"records_with_source_free_text_keys": n_source_free_text, "examples": source_free_text_examples},
        warn=(n_source_free_text > 0),
    )

    total_duration_jsonl = 0.0
    for obj in records.values():
        dur = _json_get(obj, ("segment", "processed_duration_s"))
        try:
            total_duration_jsonl += float(dur)
        except Exception:
            pass
    total_duration_expected = sum(float(v.get("processed_duration_s") or 0.0) for v in expected.values())
    unique_uploads_jsonl = len({str(obj.get("video_id")) for obj in records.values() if obj.get("video_id")})
    unique_uploads_expected = len({str(v.get("video_id")) for v in expected.values() if v.get("video_id")})

    report.add(
        "crowd_index_jsonl.summary_totals_match_mapping",
        ok=(
            unique_uploads_jsonl == unique_uploads_expected
            and _float_close(total_duration_jsonl, total_duration_expected, tol=1e-4)
        ),
        details={
            "jsonl_unique_uploads": unique_uploads_jsonl,
            "expected_unique_uploads": unique_uploads_expected,
            "jsonl_total_processed_duration_s": round(total_duration_jsonl, 6),
            "expected_total_processed_duration_s": round(total_duration_expected, 6),
            "jsonl_total_processed_duration_h": round(total_duration_jsonl / 3600.0, 2),
            "expected_total_processed_duration_h": round(total_duration_expected / 3600.0, 2),
        },
        warn=False,
    )

    summary = {
        "jsonl": read_summary,
        "expected_records_from_mapping": len(expected),
        "missing_record_count": len(missing_ids),
        "extra_record_count": len(extra_ids),
        "unique_uploads_jsonl": unique_uploads_jsonl,
        "unique_uploads_expected": unique_uploads_expected,
        "total_processed_duration_s_jsonl": round(total_duration_jsonl, 6),
        "total_processed_duration_s_expected": round(total_duration_expected, 6),
    }
    logger.info("\n=== crowd_index.jsonl validation ===")
    logger.info(json.dumps(summary, indent=2))
    return summary


def main() -> int:
    data_dir = Path(CONFIG["paths"]["data_dir"]).resolve()
    out_dir = data_dir / "_output"
    logger = _setup_logger(out_dir)
    report = Report()

    logger.info(f"Data dir: {data_dir}")

    # ---------------------------------------------------------------------
    # 0) Resolve required paths
    # ---------------------------------------------------------------------
    mapping_path = _resolve_path_maybe_absolute(data_dir, CONFIG["paths"]["mapping_csv"])
    meta_path = _resolve_path_maybe_absolute(data_dir, CONFIG["paths"]["mapping_metadata_csv"])
    jsonl_path = _resolve_path_maybe_absolute(data_dir, CONFIG["paths"].get("crowd_index_jsonl", "crowd_index.jsonl"))
    yolo_dir = _resolve_path_maybe_absolute(data_dir, CONFIG["paths"]["yolo_dir"])
    yolo_root = _infer_yolo_root(yolo_dir)

    tex_rel = CONFIG["paths"].get("main_tex")
    tex_path = _resolve_path_maybe_absolute(data_dir, tex_rel) if tex_rel else None

    report.add("path.exists.mapping_csv", mapping_path.exists(), {"path": str(mapping_path)}, warn=False)
    report.add("path.exists.mapping_metadata_csv", meta_path.exists(), {"path": str(meta_path)}, warn=False)
    report.add("path.exists.crowd_index_jsonl", jsonl_path.exists(), {"path": str(jsonl_path)}, warn=False)
    report.add("path.exists.yolo_dir", yolo_dir.exists(), {"path": str(yolo_dir)}, warn=False)
    if tex_path is not None:
        report.add("path.exists.main_tex", tex_path.exists(), {"path": str(tex_path)}, warn=True)

    if CONFIG.get("reproducibility", {}).get("enabled", True):
        collect_reproducibility_environment(data_dir, yolo_dir, out_dir, logger, report)

    if not mapping_path.exists() or not meta_path.exists() or not yolo_dir.exists():
        logger.error("Missing required inputs. Edit CONFIG['paths'].")
        (out_dir / "validate_release_report.json").write_text(json.dumps(report.to_dict(), indent=2), encoding="utf-8")
        return 1
    # ---------------------------------------------------------------------
    # 0b) Optional: export full overlap list and or interactively fix overlaps
    # ---------------------------------------------------------------------
    if EXPORT_OVERLAPS_FOUND_CSV:
        export_overlaps_found_csv(
            mapping_path=mapping_path,
            out_csv_path=(out_dir / OVERLAPS_FOUND_CSV_NAME),
            logger=logger,
            eps=float(OVERLAP_MATCH_EPS),
        )

    if FIX_OVERLAPS:
        fixed_path = out_dir / "mapping.fixed.csv"
        mapping_path = interactive_fix_overlaps_in_mapping_csv(
            mapping_path=mapping_path,
            output_path=fixed_path,
            logger=logger,
            inplace=bool(FIX_OVERLAPS_INPLACE),
            eps=float(OVERLAP_MATCH_EPS),
        )

    # ---------------------------------------------------------------------
    # 1) SHA256 manifest
    # ---------------------------------------------------------------------
    sha_lines: List[str] = []

    manifest_files: List[Path] = []
    manifest_files.extend([mapping_path, meta_path])
    if jsonl_path.exists():
        manifest_files.append(jsonl_path)
    yolo_manifest_files: List[Path] = []
    if yolo_dir.is_dir():
        # Only include a few safe suffixes, as in the original code
        for p in yolo_dir.rglob("*"):
            if not p.is_file():
                continue
            if p.suffix.lower() not in {".csv", ".txt", ".json", ".md"}:
                continue
            yolo_manifest_files.append(p)

    manifest_files.extend(sorted(yolo_manifest_files))

    for p in tqdm(manifest_files, desc="Computing SHA256", unit="file"):
        d = sha256_file(p)
        if p in {mapping_path, meta_path, jsonl_path}:
            sha_lines.append(f"{d}  {p.name}")
        else:
            rel = _manifest_relpath(p.resolve(), data_dir=data_dir, yolo_root=yolo_root, yolo_dir=yolo_dir)
            sha_lines.append(f"{d}  {rel}")

    (out_dir / "sha256_manifest.txt").write_text("\n".join(sha_lines) + "\n", encoding="utf-8")
    report.add("sha256_manifest_written", True,
               {"path": str(out_dir / "sha256_manifest.txt"), "n_entries": len(sha_lines)})

    # ---------------------------------------------------------------------
    # 2) Parse mapping.csv and compute paper-aligned rollups
    # ---------------------------------------------------------------------
    mapping_agg, video_aggs = parse_mapping_csv(mapping_path, logger, report)

    multi_continent_videos = sorted(
        [vid for vid, agg in video_aggs.items() if agg.continents and len(agg.continents) > 1]
    )

    _print_mapping_summary(mapping_agg, logger)
    _print_continent_table(mapping_agg, logger)
    _print_daynight_entries(mapping_agg, logger)
    _print_upload_daynight(mapping_agg, logger)

    # ---------------------------------------------------------------------
    # 3) Compare to expected totals (if provided)
    # ---------------------------------------------------------------------
    exp = CONFIG.get("expected", {})

    def _cmp(name: str, computed: Any, expected_key: str, tol: float = 0.0) -> None:
        expected = exp.get(expected_key)
        if expected is None:
            report.add(f"expected:{name}", True, {"computed": computed, "expected": None, "note": "not_configured"})
            return
        if isinstance(expected, int):
            ok = int(computed) == int(expected)
            report.add(f"expected:{name}", ok, {"computed": int(computed), "expected": int(expected)}, warn=not ok)
        else:
            ok = abs(float(computed) - float(expected)) <= tol
            report.add(
                f"expected:{name}",
                ok,
                {"computed": float(computed), "expected": float(expected), "delta": float(computed) - float(expected)},
                warn=not ok,
            )

    _cmp("unique_videos", mapping_agg.unique_videos, "unique_videos")
    _cmp("upload_records", mapping_agg.upload_records, "upload_records")
    _cmp("segment_records", mapping_agg.segment_records, "segment_records")
    _cmp("duration_s", int(round(mapping_agg.duration_s)), "duration_s")
    _cmp("duration_h", round(mapping_agg.duration_s / 3600.0, 2), "duration_h", tol=0.01)
    _cmp("countries", mapping_agg.unique_countries, "countries")
    _cmp("rows_locality_state_iso3", mapping_agg.unique_locality_state_iso3, "rows_locality_state_iso3")

    # ---------------------------------------------------------------------
    # 4) Load mapping_metadata.csv and cross-check
    # ---------------------------------------------------------------------
    meta, metadata_duplicate_counts = load_mapping_metadata(meta_path, logger, report)

    missing_metadata_videos = check_metadata_presence(video_aggs, meta, report)

    # Primary structured index: validate that crowd_index.jsonl is complete and current.
    validate_crowd_index_jsonl(jsonl_path, mapping_path, logger, report)

    # Figure 2 support: upload-date distribution plus caption-required omissions and incomplete 2026 flag.
    # Upload dates are now fetched from mapping.csv, not mapping_metadata.csv.
    summarise_upload_date_distribution(video_aggs, out_dir, logger, report)
    missing_in_mapping = [vid for vid in meta.keys() if vid not in video_aggs and vid != "#NAME?"]
    report.add(
        "metadata_vs_mapping.missing_in_mapping",
        ok=(len(missing_in_mapping) == 0),
        details={"missing_count": len(missing_in_mapping), "examples": missing_in_mapping[:25]},
        warn=(len(missing_in_mapping) > 0),
    )

    if EXPORT_VALIDATION_VIDEO_ISSUES_CSV:
        out_csv = out_dir / VALIDATION_VIDEO_ISSUES_CSV_NAME
        export_validation_video_issues_csv(
            out_csv_path=out_csv,
            multi_continent_videos=multi_continent_videos,
            metadata_duplicate_counts=metadata_duplicate_counts,
            missing_metadata_videos=missing_metadata_videos,
            missing_in_mapping_videos=missing_in_mapping,
            logger=logger,
        )
        report.add(
            "export.validation_video_issues_csv",
            ok=True,
            details={
                "path": str(out_csv),
                "counts": {
                    "mapping_csv.multi_continent_videos": len(multi_continent_videos),
                    "mapping_metadata.duplicate_video_rows": len(metadata_duplicate_counts),
                    "mapping_vs_metadata.missing_metadata_rows": len(missing_metadata_videos),
                    "metadata_vs_mapping.missing_in_mapping": len(missing_in_mapping),
                },
            },
        )

    # ---------------------------------------------------------------------
    # 5) Check YOLO folder
    # ---------------------------------------------------------------------
    _infos, _cov = check_yolo_folder(yolo_dir, video_aggs, report, logger)

    # ---------------------------------------------------------------------
    # 6) Optional: validate LaTeX claimed numbers
    # ---------------------------------------------------------------------
    if tex_path is not None and tex_path.exists():
        _extract_numbers_from_latex(tex_path, CONFIG.get("latex_claim_checks", []), report)

    # ---------------------------------------------------------------------
    # 7) Write report
    # ---------------------------------------------------------------------
    report_path = out_dir / "validate_release_report.json"
    report_path.write_text(json.dumps(report.to_dict(), indent=2), encoding="utf-8")

    summ = report.summary()
    logger.info("\n=== Validation summary ===")
    logger.info(json.dumps(summ, indent=2))
    logger.info(f"Report: {report_path}")

    return 1 if summ.get("fail", 0) > 0 else 0


if __name__ == "__main__":
    raise SystemExit(main())
