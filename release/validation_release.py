@dataclass(frozen=True)
class _SegOcc:
    video: str
    row_index: int      # 0 based data row index
    row_number: int     # 1 based data row number (excluding header)
    location: str       # locality|state|country
    start: float
    end: float


def dump_list_compact(v: Any) -> str:
    """Serialise a (nested) list in the compact style of mapping.csv: strings unquoted, no spaces after commas."""
    if isinstance(v, list):
        return "[" + ",".join(dump_list_compact(x) for x in v) + "]"
    if v is None:
        return ""
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        if math.isfinite(v) and abs(v - round(v)) < 1e-12:
            return str(int(round(v)))
        return repr(v)
    return str(v).strip()


def _dump_list(v: Any) -> str:
    return dump_list_compact(v) if WRITE_MAPPING_LISTS_COMPACT else repr(v)


def _segment_matches(s_raw: Any, e_raw: Any, start: float, end: float, eps: float) -> bool:
    s, e = _to_float_maybe(s_raw), _to_float_maybe(e_raw)
    return s is not None and e is not None and abs(s - start) <= eps and abs(e - end) <= eps


def _build_occurrences_for_all_videos(rows: List[Dict[str, Any]]) -> Dict[str, List[_SegOcc]]:
    """video -> its valid segments (0 <= start < end) over all mapping rows."""
    by_vid: Dict[str, List[_SegOcc]] = defaultdict(list)
    for ridx, r in enumerate(rows):
        loc = "|".join((r.get(k) or "").strip() for k in ("locality", "state", "country"))
        vids = parse_videos(r.get("videos"))
        st_lol = parse_list(r.get("start_time"))
        en_lol = parse_list(r.get("end_time"))
        for i in range(min(len(vids), len(st_lol), len(en_lol))):
            starts = st_lol[i] if isinstance(st_lol[i], list) else []
            ends = en_lol[i] if isinstance(en_lol[i], list) else []
            for s_raw, e_raw in zip(starts, ends):
                s, e = _to_float_maybe(s_raw), _to_float_maybe(e_raw)
                if s is not None and e is not None and 0 <= s < e:
                    by_vid[vids[i]].append(_SegOcc(vids[i], ridx, ridx + 1, loc, s, e))
    return by_vid


def _detect_overlaps_for_video(occs: List[_SegOcc]) -> List[Tuple[_SegOcc, _SegOcc]]:
    """Overlapping pairs of one video's segments, sweeping in start order and keeping the later-ending one active."""
    if len(occs) < 2:
        return []
    segs_sorted = sorted(occs, key=lambda o: (o.start, o.end, o.location, o.row_number))
    overlaps: List[Tuple[_SegOcc, _SegOcc]] = []
    prev = segs_sorted[0]
    for cur in segs_sorted[1:]:
        if cur.start < prev.end:
            overlaps.append((prev, cur))
            if cur.end <= prev.end:
                continue
        prev = cur
    return overlaps


def export_overlaps_found_csv(mapping_path: Path, out_csv_path: Path, logger: logging.Logger) -> int:
    """Scan mapping.csv for overlapping segments and write every overlap pair to a CSV; returns the pair count."""
    _fieldnames, rows = _read_csv_dicts(mapping_path)
    if not rows:
        return 0
    by_vid = _build_occurrences_for_all_videos(rows)

    out_csv_path.parent.mkdir(parents=True, exist_ok=True)
    n_pairs = 0
    with out_csv_path.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["video", "a_row_number", "a_location", "a_start", "a_end",
                    "b_row_number", "b_location", "b_start", "b_end", "overlap_s"])
        for vid in sorted(by_vid):
            for a, b in _detect_overlaps_for_video(by_vid[vid]):
                overlap_s = max(0.0, min(a.end, b.end) - max(a.start, b.start))
                w.writerow([vid, a.row_number, a.location, a.start, a.end,
                            b.row_number, b.location, b.start, b.end, overlap_s])
                n_pairs += 1

    logger.info(f"Overlaps CSV written: {out_csv_path} (pairs: {n_pairs})")
    return n_pairs


def _remove_inner_segment(row: Dict[str, Any], outer_i: int, start: float, end: float, eps: float) -> bool:
    """Delete segment [start, end] of the row's video outer_i with its time_of_day and vehicle_type values;
    True when it was found."""
    vids = parse_videos(row.get("videos"))
    st_lol = parse_list(row.get("start_time"))
    en_lol = parse_list(row.get("end_time"))
    tod_lol = parse_list(row.get("time_of_day"))
    veh_lol = parse_list(row.get("vehicle_type")) if "vehicle_type" in row else None

    if not 0 <= outer_i < min(len(vids), len(st_lol), len(en_lol)):
        return False
    starts, ends = st_lol[outer_i], en_lol[outer_i]
    if not (isinstance(starts, list) and isinstance(ends, list)):
        return False
    j = next((j for j, (s, e) in enumerate(zip(starts, ends)) if _segment_matches(s, e, start, end, eps)), None)
    if j is None:
        return False

    starts.pop(j)
    ends.pop(j)
    for lol in (tod_lol, veh_lol):
        if isinstance(lol, list) and outer_i < len(lol) and isinstance(lol[outer_i], list) and j < len(lol[outer_i]):
            lol[outer_i].pop(j)

    row["start_time"] = _dump_list(st_lol)
    row["end_time"] = _dump_list(en_lol)
    if "time_of_day" in row:
        row["time_of_day"] = _dump_list(tod_lol)
    if veh_lol is not None:
        row["vehicle_type"] = _dump_list(veh_lol)
    return True


def _maybe_remove_empty_video_outer_entry(row: Dict[str, Any], outer_i: int, fieldnames: List[str]) -> bool:
    """If video outer_i of the row has no segments left, remove it from videos and every list column with one entry
    per video; True when removed."""
    vids = parse_videos(row.get("videos"))
    st_lol = parse_list(row.get("start_time"))
    en_lol = parse_list(row.get("end_time"))
    if outer_i >= min(len(vids), len(st_lol), len(en_lol)):
        return False
    if st_lol[outer_i] != [] or en_lol[outer_i] != []:
        return False

    for col in fieldnames:
        raw = row.get(col)
        if not (isinstance(raw, str) and raw.strip().startswith("[") and raw.strip().endswith("]")):
            continue
        parsed = parse_videos(raw) if col == "videos" else parse_list(raw)
        if len(parsed) == len(vids):
            parsed.pop(outer_i)
            row[col] = _dump_list(parsed)
    return True


def _find_outer_index_for_segment(row: Dict[str, Any], video_id: str, start: float,
                                  end: float, eps: float) -> Optional[int]:
    """Index of video_id in the row's videos whose segments include [start, end], else None."""
    st_lol = parse_list(row.get("start_time"))
    en_lol = parse_list(row.get("end_time"))
    for i, v in enumerate(parse_videos(row.get("videos"))):
        if v != video_id or i >= len(st_lol) or i >= len(en_lol):
            continue
        starts, ends = st_lol[i], en_lol[i]
        if isinstance(starts, list) and isinstance(ends, list) and any(
                _segment_matches(s, e, start, end, eps) for s, e in zip(starts, ends)):
            return i
    return None


def _overlap_signature(vid: str, a: _SegOcc, b: _SegOcc) -> Tuple[str, int, float, float, int, float, float]:
    return vid, a.row_index, round(a.start, 3), round(a.end, 3), b.row_index, round(b.start, 3), round(b.end, 3)


def interactive_fix_overlaps_in_mapping_csv(
    mapping_path: Path,
    output_path: Path,
    logger: logging.Logger,
    inplace: bool,
    eps: float,
) -> Path:
    """
    Interactively resolve overlaps by asking which side to delete; returns the path of the mapping to validate.
    Deleting means deleting the segment and all aligned values for that segment.
    If a video outer entry becomes empty, it is removed from videos and all aligned list columns.
    """
    if not sys.stdin.isatty():
        logger.warning("Interactive overlap fixer is enabled but stdin is not a TTY, skipping.")
        return mapping_path

    fieldnames, rows = _read_csv_dicts(mapping_path)
    if not rows:
        logger.info("mapping.csv is empty, nothing to fix.")
        return mapping_path

    by_vid = _build_occurrences_for_all_videos(rows)
    vids_with_overlaps = sorted(vid for vid, occs in by_vid.items() if _detect_overlaps_for_video(occs))
    if not vids_with_overlaps:
        logger.info("No overlapping segments found. No changes made.")
        return mapping_path

    logger.info(f"Found overlaps in {len(vids_with_overlaps)} videos. Starting interactive cleanup.")

    def _apply_delete(target: _SegOcc) -> None:
        row = rows[target.row_index]
        outer_i = _find_outer_index_for_segment(row, target.video, target.start, target.end, eps=eps)
        if outer_i is None:
            logger.warning(
                f"Could not find segment in row {target.row_number} for deletion: {target.video} [{target.start},{target.end}]"  # noqa:E501
            )
            return
        if not _remove_inner_segment(row, outer_i, target.start, target.end, eps=eps):
            logger.warning(
                f"Failed to delete segment in row {target.row_number}: {target.video} [{target.start},{target.end}]"  # noqa:E501
            )
            return

        if _maybe_remove_empty_video_outer_entry(row, outer_i, fieldnames):
            by_vid[target.video] = [o for o in by_vid.get(target.video, []) if o.row_index != target.row_index]
        else:
            by_vid[target.video] = [
                o for o in by_vid.get(target.video, [])
                if not (o.row_index == target.row_index and abs(o.start - target.start) <= eps
                        and abs(o.end - target.end) <= eps)
            ]

    skipped_pairs: Set[Tuple[str, int, float, float, int, float, float]] = set()
    quit_requested = False
    for vid in vids_with_overlaps:
        while not quit_requested:
            overlaps = _detect_overlaps_for_video(by_vid.get(vid, []))
            if not overlaps:
                break
            chosen = next(((a, b) for a, b in overlaps if _overlap_signature(vid, a, b) not in skipped_pairs), None)
            if chosen is None:
                logger.warning(f"All remaining overlaps for video {vid} were kept. Leaving them as is.")
                break

            a, b = chosen
            logger.info("")
            logger.info(f"Video: {vid}")
            logger.info("Overlap detected. Choose what to delete.")
            logger.info(f"A) row {a.row_number}  {a.location}  [{a.start} , {a.end}]")
            logger.info(f"B) row {b.row_number}  {b.location}  [{b.start} , {b.end}]")
            logger.info("Options: 1 delete A, 2 delete B, 3 delete both, k keep both, q quit")
            choice = input("Your choice: ").strip().lower()

            if choice == "q":
                quit_requested = True
                logger.info("Quitting interactive overlap fixer early.")
            elif choice in ("1", "2", "3"):
                for target in {"1": [a], "2": [b], "3": [a, b]}[choice]:
                    _apply_delete(target)
            else:
                if choice not in ("k", ""):
                    logger.warning("Unrecognised choice. Keeping both for now.")
                skipped_pairs.add(_overlap_signature(vid, a, b))
        if quit_requested:
            break

    target_path = mapping_path.with_suffix(".tmp.fixed.csv") if inplace else output_path
    target_path.parent.mkdir(parents=True, exist_ok=True)
    with target_path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
    if inplace:
        target_path.replace(mapping_path)
        logger.info(f"Wrote fixed mapping in place: {mapping_path}")
        return mapping_path
    logger.info(f"Wrote fixed mapping to: {output_path}")
    return output_path


