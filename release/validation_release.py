def _float_close(a: Any, b: Any, tol: float = 1e-6) -> bool:
    """True when a and b are finite numbers within tol."""
    af, bf = _to_float_maybe(a), _to_float_maybe(b)
    return af is not None and bf is not None and abs(af - bf) <= tol


