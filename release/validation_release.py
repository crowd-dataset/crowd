def _valid_upload_ymd(year: int, month: int, day: int) -> Optional[Tuple[int, int, int]]:
    """Return a validated (year, month, day), otherwise None."""
    if not (1900 <= year <= 2100 and 1 <= month <= 12 and 1 <= day <= calendar.monthrange(year, month)[1]):
        return None
    return year, month, day


def _normalise_upload_date(raw: Any) -> Optional[Tuple[int, int, int]]:
    """Return (year, month, day) for upload dates from mapping.csv or metadata.

    Supported forms include:
      - YYYY-MM-DD / YYYY/MM/DD
      - YYYYMMDD
      - compact mapping.csv values such as 29082023, 3042024, 9122023
        interpreted as DDMMYYYY or DMMYYYY.
    """
    if raw is None:
        return None

    s = str(raw).strip()
    if not s or s.lower() in {"nan", "none", "null", "na", "n/a", "unknown", "unavailable", "#n/a"}:
        return None

    # Preferred form from YouTube metadata: YYYY-MM-DD, with / also accepted; then compact YYYYMMDD.
    for pattern in (r"(?P<year>20\d{2}|19\d{2})[-/](?P<month>0?[1-9]|1[0-2])[-/](?P<day>0?[1-9]|[12]\d|3[01])",
                    r"(?P<year>20\d{2}|19\d{2})(?P<month>0[1-9]|1[0-2])(?P<day>0[1-9]|[12]\d|3[01])"):
        m = re.search(pattern, s)
        if m:
            return _valid_upload_ymd(int(m.group("year")), int(m.group("month")), int(m.group("day")))

    # mapping.csv stores many upload dates as compact DDMMYYYY / DMMYYYY values.
    # Examples: 29082023 -> 2023-08-29, 3042024 -> 2024-04-03, 9122023 -> 2023-12-09.
    digits = re.sub(r"\D", "", s)
    if 5 <= len(digits) <= 8:
        year = int(digits[-4:])
        day_month = digits[:-4]
        # Prefer a two-digit month (the mapping.csv format), then a one-digit month for rare DDMYYYY-like values.
        for n_month in (2, 1):
            if len(day_month) > n_month:
                parsed = _valid_upload_ymd(year, int(day_month[-n_month:]), int(day_month[:-n_month]))
                if parsed is not None:
                    return parsed
    return None


def summarise_upload_date_distribution(
    video_aggs: Dict[str, VideoAgg],
    out_dir: Path,
    logger: logging.Logger,
    report: Report,
) -> Dict[str, Any]:
    """Export upload-date counts needed for Figure 2 and its caption.

    Upload dates are read from mapping.csv through ``VideoAgg.upload_dates``.
    Counts are over unique videos that appear in mapping.csv, not over
    metadata-only rows.
    """
    year_counts: Counter[int] = Counter()
    quarter_counts: Counter[Tuple[int, int]] = Counter()
    missing_examples: List[Dict[str, Any]] = []
    conflicting_date_examples: List[Dict[str, Any]] = []
    videos_with_conflicting_valid_dates = 0
    omitted_unavailable = 0
    first_dates: List[Tuple[int, int, int]] = []

    def ymd(d: Tuple[int, int, int]) -> str:
        return f"{d[0]:04d}-{d[1]:02d}-{d[2]:02d}"

    for vid in sorted(video_aggs):
        raw_dates = [str(v).strip() for v in video_aggs[vid].upload_dates if str(v).strip()]
        parsed_dates = [p for p in map(_normalise_upload_date, raw_dates) if p is not None]

        if not parsed_dates:
            omitted_unavailable += 1
            if len(missing_examples) < MAX_EXAMPLES:
                missing_examples.append({
                    "video": vid,
                    "raw_upload_dates": raw_dates,
                    "reason": "missing_or_unparseable_upload_date_in_mapping_csv",
                })
            continue

        unique_valid_dates = sorted(set(parsed_dates))
        if len(unique_valid_dates) > 1:
            videos_with_conflicting_valid_dates += 1
            if len(conflicting_date_examples) < MAX_EXAMPLES:
                conflicting_date_examples.append({
                    "video": vid,
                    "raw_upload_dates": raw_dates,
                    "valid_dates": [ymd(d) for d in unique_valid_dates],
                })

        # The first valid mapping.csv upload date counts; the conflict count above flags videos with more than one.
        year, month, _day = parsed_dates[0]
        year_counts[year] += 1
        quarter_counts[(year, (month - 1) // 3 + 1)] += 1
        first_dates.append(parsed_dates[0])

    year_csv_path = out_dir / "upload_date_distribution_by_year.csv"
    quarter_csv_path = out_dir / "upload_date_distribution_by_quarter.csv"
    summary_json_path = out_dir / "upload_date_figure_summary.json"

    with year_csv_path.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["year", "videos", "incomplete_period"])
        w.writerows([year, year_counts[year], year == 2026] for year in sorted(year_counts))

    with quarter_csv_path.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["year", "quarter", "period", "videos", "incomplete_period"])
        w.writerows([year, quarter, f"{year}-Q{quarter}", quarter_counts[(year, quarter)], year == 2026]
                    for year, quarter in sorted(quarter_counts))

