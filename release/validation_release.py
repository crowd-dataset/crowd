def load_mapping_metadata(
    path: Path,
    logger: logging.Logger,
    report: Report,
) -> Tuple[Dict[str, int], Dict[str, int]]:
    """(video -> its first data row in mapping_metadata.csv, video -> number of duplicate rows)."""
    total_rows = count_csv_data_rows(path)
    first_seen_row: Dict[str, int] = {}
    dup_video_counts: Counter[str] = Counter()
    dup_examples: List[Dict[str, Any]] = []

    with path.open("r", encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        cols = reader.fieldnames or []
        missing = sorted({"video", "segments"} - set(cols))
        report.add(
            "mapping_metadata.required_columns",
            ok=not missing,
            details={"missing": missing, "present": cols},
            warn=bool(missing),
        )

        rows = tqdm(reader, total=total_rows, desc="Loading mapping_metadata.csv", unit="row")
        for rownum, r in enumerate(rows, start=1):  # data row number (excluding header)
            video = (r.get("video") or "").strip()
            if not video:
                continue
            if video in first_seen_row:  # keep the first occurrence
                dup_video_counts[video] += 1
                if len(dup_examples) < MAX_EXAMPLES:
                    dup_examples.append({"video": video, "first_row": first_seen_row[video], "duplicate_row": rownum})
            else:
                first_seen_row[video] = rownum

    dup_row_count = sum(dup_video_counts.values())
    report.add(
        "mapping_metadata.duplicate_video_rows",
        ok=(dup_row_count == 0),
        details={"duplicate_row_count": dup_row_count, "examples": dup_examples},
        warn=(dup_row_count > 0),
    )
    report.add(
        "mapping_metadata.unique_video_keys",
        ok=True,
        details={"n_unique_videos": len(first_seen_row), "n_rows_total": total_rows,
                 "duplicate_row_count": dup_row_count},
    )
    return first_seen_row, dict(dup_video_counts)


