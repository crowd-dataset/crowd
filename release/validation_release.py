class _CountryValues:
    """One per-country column of mapping.csv (avg_height, ...): all rows of a country should have the same value."""

    def __init__(self, name: str, column: str) -> None:
        self.name, self.column = name, column
        self.values: Dict[str, Set[str]] = defaultdict(set)
        self.rows: Counter[str] = Counter()
        self.missing: Counter[str] = Counter()
        self.n_invalid = 0
        self.invalid_examples: List[Dict[str, Any]] = []

    def add(self, row: Dict[str, Any], row_number: int, country: str, state: str, locality: str) -> None:
        self.rows[country] += 1
        raw = (row.get(self.column) or "").strip()
        if raw == "" or raw.lower() in MISSING_TEXT:
            self.missing[country] += 1
            return
        num = _num_from_str(raw)
        if num is None or not math.isfinite(num):
            self.n_invalid += 1
            self.values[country].add(raw)
            if len(self.invalid_examples) < MAX_EXAMPLES:
                self.invalid_examples.append(
                    {"row": row_number, "country": country, "state": state, "locality": locality, "value": raw})
        else:
            self.values[country].add(f"{round(num, 6):.6f}".rstrip("0").rstrip("."))

    def add_checks(self, report: Report) -> None:
        """Add the <name>_consistent_by_country and <name>_values_parseable checks."""
        mismatched = [co for co, vals in self.values.items() if len(vals) > 1]
        examples = [
            {
                "country": co,
                "rows": self.rows[co],
                "unique_value_count": len(self.values[co]),
                "unique_values": sorted(self.values[co])[:10],
                "missing_rows": self.missing[co],
            }
            for co in sorted(mismatched, key=lambda x: (-self.rows[x], x))[:MAX_EXAMPLES]
        ]
        report.add(
            f"mapping_csv.{self.name}_consistent_by_country",
            ok=not mismatched,
            details={"mismatch_country_count": len(mismatched), "examples": examples},
            warn=bool(mismatched),
        )
        report.add(
            f"mapping_csv.{self.name}_values_parseable",
            ok=self.n_invalid == 0,
            details={"invalid_value_count": self.n_invalid, "examples": self.invalid_examples},
            warn=self.n_invalid > 0,
        )


def _per_country_columns(colset: Set[str], report: Report) -> List[_CountryValues]:
    """Report which per-country columns mapping.csv has; a checker for each one present."""
    out: List[_CountryValues] = []
    for name, candidates, with_name in (
        ("avg_height", ["avg_height"], False),
        ("med_age", ["med_age"], False),
        ("traffic_mortality", ["traffic_mortality", "traffic mortality"], True),
        ("literacy_rate", ["literacy_rate", "literacy rate"], True),
    ):
        column = next((c for c in candidates if c in colset), "")
        details: Dict[str, Any] = {"present": bool(column)}
        if with_name:
            details["column_name"] = column or None
        report.add(f"mapping_csv.{name}_column_present", ok=bool(column), details=details, warn=not column)
        if column:
            out.append(_CountryValues(name, column))
    return out


def _invalid_codes(lol: List[List[int]], allowed: Set[int], where: Dict[str, Any],
                   examples: List[Dict[str, Any]]) -> int:
    """Number of values in a nested code list that are not allowed, adding up to 25 examples."""
    n = 0
    for outer_i, codes in enumerate(lol):
        for inner_i, value in enumerate(codes):
            if value not in allowed:
                n += 1
                if len(examples) < MAX_EXAMPLES:
                    examples.append({**where, "outer_index": outer_i, "inner_index": inner_i, "value": value})
    return n


def _segment_problem(s: Any, e: Any) -> Tuple[Optional[str], Any, Any]:
    """(reason the segment is invalid or None, start, end as floats when they are numbers)."""
    try:
        s2, e2 = float(s), float(e)
    except Exception:
        return "non_numeric", s, e
    if not (math.isfinite(s2) and math.isfinite(e2)):
        return "non_finite", s2, e2
    if s2 < 0 or e2 < 0 or e2 <= s2:
        return "invalid_order_or_negative", s2, e2
    return None, s2, e2


def _check_segment_overlaps(video_segment_details: Dict[str, List[_SegOcc]], report: Report) -> None:
    """A video should not have overlapping segments, nor the same (start, end) under more than one location."""
    n_overlapping_pairs = 0
    overlap_examples: List[Dict[str, Any]] = []
    n_duplicate_segments_across_locations = 0
    duplicate_segment_examples: List[Dict[str, Any]] = []

    for vid, seg_list in tqdm(video_segment_details.items(), total=len(video_segment_details),
                              desc="Checking segment overlaps", unit="video"):
        if len(seg_list) < 2:
            continue

        for prev, cur in _detect_overlaps_for_video(seg_list):
            n_overlapping_pairs += 1
            if len(overlap_examples) < MAX_EXAMPLES:
                overlap_examples.append({
                    "video": vid,
                    "prev": {"start": prev.start, "end": prev.end, "location": prev.location, "row": prev.row_number},
                    "curr": {"start": cur.start, "end": cur.end, "location": cur.location, "row": cur.row_number},
                })

        seg_to_locs: Dict[Tuple[float, float], Set[str]] = defaultdict(set)
        seg_to_rows: Dict[Tuple[float, float], Set[int]] = defaultdict(set)
        for o in seg_list:
            key = (round(o.start, 3), round(o.end, 3))
            seg_to_locs[key].add(o.location)
            seg_to_rows[key].add(o.row_number)
        for (s, e), locs in seg_to_locs.items():
            if len(locs) > 1:
                n_duplicate_segments_across_locations += 1
                if len(duplicate_segment_examples) < MAX_EXAMPLES:
                    duplicate_segment_examples.append({
                        "video": vid,
                        "start": s,
                        "end": e,
                        "location_count": len(locs),
                        "locations": sorted(locs)[:10],
                        "rows": sorted(seg_to_rows[(s, e)])[:15],
                    })

    report.add(
        "mapping_csv.video_segments_non_overlapping",
        ok=(n_overlapping_pairs == 0),
        details={"overlapping_pair_count": n_overlapping_pairs, "examples": overlap_examples},
        warn=(n_overlapping_pairs > 0),
    )
    report.add(
        "mapping_csv.video_segment_duplicate_locations",
        ok=(n_duplicate_segments_across_locations == 0),
        details={
            "duplicate_segment_count": n_duplicate_segments_across_locations,
            "examples": duplicate_segment_examples,
        },
        warn=(n_duplicate_segments_across_locations > 0),
    )


def parse_mapping_csv(path: Path, logger: logging.Logger, report: Report) -> Tuple[MappingAgg, Dict[str, VideoAgg]]:
    """Read mapping.csv once: the paper's rollups, the per-video aggregates, and all mapping_csv.* checks."""
    allowed_cont = set(CONFIG["allowed"]["continents"])
    allowed_tod_vals = set(CONFIG["allowed"]["time_of_day_codes"])  # {0, 1}
    allowed_vehicle_vals = set(CONFIG["allowed"]["vehicle_type_codes"])

    rows = 0
    locality_state_iso3_keys: Set[str] = set()
    countries: Set[str] = set()
    upload_records = 0
    segment_records = 0
    duration_s = 0.0
    cont_seg: Dict[str, int] = defaultdict(int)
    cont_dur: Dict[str, float] = defaultdict(float)
    cont_day: Dict[str, int] = defaultdict(int)
    cont_night: Dict[str, int] = defaultdict(int)
    video_aggs: Dict[str, VideoAgg] = {}

    n_rows_outer_mismatch = 0
    n_bad_segment_pairs = 0
    bad_segment_examples: List[Dict[str, Any]] = []
    n_rows_zero_videos = 0
    zero_video_examples: List[Dict[str, Any]] = []
    n_invalid_tod_values = 0
    invalid_tod_examples: List[Dict[str, Any]] = []
    n_invalid_vehicle_values = 0
    invalid_vehicle_examples: List[Dict[str, Any]] = []
    locality_state_country_counts: Counter[str] = Counter()
    video_segment_details: Dict[str, List[_SegOcc]] = defaultdict(list)

    total_rows = count_csv_data_rows(path)

    with path.open("r", encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        cols = reader.fieldnames or []
        required = {
            "continent", "country", "locality", "iso3", "videos",
            "time_of_day", "start_time", "end_time", "upload_date",
        }
        missing = sorted(required - set(cols))
        report.add(
            "mapping_csv.required_columns",
            ok=not missing,
            details={"missing": missing, "present": cols},
            warn=bool(missing),
        )
        colset = set(cols)
        has_vehicle = "vehicle_type" in colset
        per_country = _per_country_columns(colset, report)

        for r in tqdm(reader, total=total_rows, desc="Parsing mapping.csv", unit="row"):
            rows += 1
            continent, country, locality, iso3, state = (
                (r.get(k) or "").strip() for k in ("continent", "country", "locality", "iso3", "state"))
            loc_key_csc = f"{locality}|{state}|{country}"

            if country:
                countries.add(country)
                for column in per_country:
                    column.add(r, rows, country, state, locality)
            if locality and iso3:
                locality_state_iso3_keys.add(f"{locality}|{state}|{iso3}")
            if locality and country:
                locality_state_country_counts[loc_key_csc] += 1

            vids = parse_videos(r.get("videos"))
            upload_dates = [str(v).strip() for v in parse_list(r.get("upload_date"))]
            tod_lol = norm_list_of_lists_int(r.get("time_of_day"))
            st_lol = norm_list_of_lists_float(r.get("start_time"))
            en_lol = norm_list_of_lists_float(r.get("end_time"))
            veh_lol = norm_list_of_lists_int(r.get("vehicle_type")) if has_vehicle else []

            where = {"row": rows, "continent": continent, "country": country, "state": state,
                     "locality": locality, "iso3": iso3}
            if not vids:
                n_rows_zero_videos += 1
                if len(zero_video_examples) < MAX_EXAMPLES:
                    zero_video_examples.append(dict(where))
            n_invalid_tod_values += _invalid_codes(tod_lol, allowed_tod_vals, where, invalid_tod_examples)
            n_invalid_vehicle_values += _invalid_codes(veh_lol, allowed_vehicle_vals, where, invalid_vehicle_examples)

            upload_records += len(vids)

            # Outer lists should all have one entry per video; rollups use only the aligned part (zip truncation)
            outer_lens = [len(vids), len(upload_dates), len(tod_lol), len(st_lol), len(en_lol)]
            if has_vehicle:
                outer_lens.append(len(veh_lol))
            if len(set(outer_lens)) != 1:
                n_rows_outer_mismatch += 1

            if continent and continent not in allowed_cont:
                report.add(
                    "mapping_csv.continent_allowed",
                    ok=False,
                    details={"continent": continent, "row": rows},
                    warn=True,
                )

            row_seg_records = 0
            row_dur = 0.0
            for i in range(min(outer_lens)):
                vid = vids[i]
                tods = tod_lol[i]
                row_seg_records += len(tods)
                agg = video_aggs.setdefault(vid, VideoAgg())
                for s, e in zip(st_lol[i], en_lol[i]):
                    reason, s, e = _segment_problem(s, e)
                    if reason:
                        n_bad_segment_pairs += 1
                        if len(bad_segment_examples) < MAX_EXAMPLES:
                            bad_segment_examples.append({"row": rows, "video": vid, "start": s, "end": e,
                                                         "reason": reason})
                        continue
                    row_dur += float(_jsonl_processed_duration_seconds(s, e) or 0.0)
                    video_segment_details[vid].append(_SegOcc(vid, rows - 1, rows, loc_key_csc, s, e))
                    agg.segments.add((s, e))

                agg.upload_dates.append(upload_dates[i])
                if continent:
                    agg.continents[continent] += 1
                agg.has_day = agg.has_day or 0 in tods
                agg.has_night = agg.has_night or 1 in tods

            if continent:
                labels = [t for tods in tod_lol[:len(vids)] for t in tods]
                cont_seg[continent] += row_seg_records
                cont_dur[continent] += row_dur
                cont_day[continent] += labels.count(0)
                cont_night[continent] += labels.count(1)

            segment_records += row_seg_records
            duration_s += row_dur

    n_multi_cont = sum(1 for a in video_aggs.values() if len(a.continents) > 1)
    global_dn = Counter(
        "both_day_night" if a.has_day and a.has_night else
        "only_day" if a.has_day else "only_night" if a.has_night else "unknown"
        for a in video_aggs.values()
    )

    agg = MappingAgg(
        rows=rows,
        unique_locality_state_iso3=len(locality_state_iso3_keys),
        unique_countries=len(countries),
        upload_records=upload_records,
        unique_videos=len(video_aggs),
        segment_records=segment_records,
        duration_s=duration_s,
        continent_segment_records=dict(cont_seg),
        continent_duration_s=dict(cont_dur),
        continent_day_entries=dict(cont_day),
        continent_night_entries=dict(cont_night),
        global_upload_daynight=dict(global_dn),
    )

    report.add(
        "mapping_csv.outer_list_alignment",
        ok=(n_rows_outer_mismatch == 0),
        details={"rows": rows, "rows_with_outer_len_mismatch": n_rows_outer_mismatch},
        warn=(n_rows_outer_mismatch > 0),
    )
    report.add(
        "mapping_csv.multi_continent_videos",
        ok=(n_multi_cont == 0),
        details={"videos_with_multiple_continents": n_multi_cont},
        warn=(n_multi_cont > 0),
    )
    report.add(
        "mapping_csv.segment_pairs_valid",
        ok=(n_bad_segment_pairs == 0),
        details={"bad_pair_count": n_bad_segment_pairs, "examples": bad_segment_examples},
        warn=(n_bad_segment_pairs > 0),
    )
    report.add(
        "mapping_csv.rows_with_zero_videos",
        ok=(n_rows_zero_videos == 0),
        details={"rows_with_zero_videos": n_rows_zero_videos, "examples": zero_video_examples},
        warn=(n_rows_zero_videos > 0),
    )
    report.add(
        "mapping_csv.time_of_day_values_valid",
        ok=(n_invalid_tod_values == 0),
        details={"invalid_value_count": n_invalid_tod_values, "examples": invalid_tod_examples,
                 "allowed_values": sorted(allowed_tod_vals)},
        warn=(n_invalid_tod_values > 0),
    )
    report.add(
        "mapping_csv.vehicle_type_values_valid",
        ok=(n_invalid_vehicle_values == 0),
        details={
            "invalid_value_count": n_invalid_vehicle_values,
            "examples": invalid_vehicle_examples,
            "allowed_values": sorted(allowed_vehicle_vals),
            "allowed_labels": {str(k): v for k, v in sorted(CONFIG["allowed"]["vehicle_type_codes"].items())},
        },
        warn=(n_invalid_vehicle_values > 0),
    )

    dups = [(k, v) for k, v in locality_state_country_counts.items() if v > 1]
    dup_examples = [
        dict(zip(("locality", "state", "country"), k.split("|", 2)), rows=v)
        for k, v in sorted(dups, key=lambda kv: (-kv[1], kv[0]))[:MAX_EXAMPLES]
    ]
    report.add(
        "mapping_csv.duplicate_locality_state_country",
        ok=(len(dups) == 0),
        details={"duplicate_key_count": len(dups), "examples": dup_examples},
        warn=(len(dups) > 0),
    )

    for column in per_country:
        column.add_checks(report)

    _check_segment_overlaps(video_segment_details, report)
    return agg, video_aggs


