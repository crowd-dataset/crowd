def _jsonl_processed_duration_seconds(start: float, end: float) -> Optional[float]:
    """Processed duration of a segment (end - 1 s, as the detector pipeline trims it)."""
    return make_crowd_jsonl._processed_duration(start, end)[1]


def _jsonl_read_existing(jsonl_path: Path, report: Report) -> Tuple[Dict[str, Dict[str, Any]], Dict[str, Any]]:
    """Read crowd_index.jsonl into segment_id -> record, reporting unreadable lines and duplicate ids."""
    records: Dict[str, Dict[str, Any]] = {}
    bad_lines: List[int] = []
    duplicates: List[str] = []
    n_lines = 0
    if jsonl_path.exists():
        with jsonl_path.open(encoding="utf-8") as f:
            for n_lines, line in enumerate(f, start=1):
                if not line.strip():
                    continue
                try:
                    obj = json.loads(line)
                except json.JSONDecodeError:
                    bad_lines.append(n_lines)
                    continue
                segment_id = obj.get("segment_id") if isinstance(obj, dict) else None
                if not segment_id:
                    bad_lines.append(n_lines)
                elif segment_id in records:
                    duplicates.append(segment_id)
                else:
                    records[segment_id] = obj
    summary = {"exists": jsonl_path.exists(), "lines": n_lines, "records": len(records),
               "unreadable_lines": len(bad_lines), "duplicate_segment_ids": len(duplicates)}
    report.add("crowd_index_jsonl.readable", ok=jsonl_path.exists() and not bad_lines and not duplicates,
               details={**summary, "unreadable_line_examples": bad_lines[:25], "duplicate_examples": duplicates[:25]})
    return records, summary


def _jsonl_expected_records_from_mapping(mapping_path: Path, meta_path: Path,
                                         logger: logging.Logger) -> Dict[str, Dict[str, Any]]:
    """segment_id -> the fields the JSONL must carry for it, rebuilt from the mapping with make_crowd_jsonl."""
    records, summary = make_crowd_jsonl.build_records(mapping_path, meta_path)
    logger.info(f"Expected {summary['jsonl_records']} JSONL records from {mapping_path.name}.")
    return {r["segment_id"]: {"video_id": r["video_id"], "start_time_s": r["start_time_s"],
                              "end_time_s": r["end_time_s"],
                              "processed_duration_s": _jsonl_processed_duration_seconds(r["start_time_s"],
                                                                                        r["end_time_s"])}
            for r in records}


def _add_example(examples: List[Dict[str, Any]], example: Dict[str, Any]) -> None:
    if len(examples) < MAX_EXAMPLES:
        examples.append(example)


def validate_crowd_index_jsonl(
    jsonl_path: Path,
    mapping_path: Path,
    meta_path: Path,
    logger: logging.Logger,
    report: Report,
) -> Dict[str, Any]:
    """Validate that crowd_index.jsonl is valid, complete, and current."""
    records, read_summary = _jsonl_read_existing(jsonl_path, report)
    expected = _jsonl_expected_records_from_mapping(mapping_path, meta_path, logger)

    missing_ids = sorted(expected.keys() - records.keys())
    extra_ids = sorted(records.keys() - expected.keys())
    report.add(
        "crowd_index_jsonl.complete_vs_mapping",
        ok=(len(missing_ids) == 0 and len(extra_ids) == 0 and len(records) == len(expected)),
        details={
            "expected_records_from_mapping": len(expected),
            "jsonl_unique_records": len(records),
            "missing_record_count": len(missing_ids),
            "extra_record_count": len(extra_ids),
            "missing_examples": missing_ids[:25],
            "extra_examples": extra_ids[:25],
        },
        warn=False,
    )

    required_top = {"segment_id", "video_id", "youtube_url", "start_time_s", "end_time_s", "upload_date",
                    "time_of_day_code", "time_of_day_name", "vehicle_type_code", "vehicle_type_name",
                    "location", "mapping_row_number", "metadata", "mapping_extra"}
    # Keys that must exist in `location`; a missing source value is an explicit null, never an omitted key.
    required_location = ("locality", "country", "iso3", "continent", "lat", "lon")
    # Numeric codes must be present and non-null; the *_name and upload_date fields may legitimately be null.
    required_not_null = ("segment_id", "video_id", "youtube_url", "start_time_s", "end_time_s")
    free_text_keys = {"title", "description", "channel", "chapters", "tags", "categories"}

    missing_required_examples: List[Dict[str, Any]] = []
    bad_value_examples: List[Dict[str, Any]] = []
    mismatch_examples: List[Dict[str, Any]] = []
    source_free_text_examples: List[Dict[str, Any]] = []
    n_missing_required = 0
    n_bad_governance_values = 0
    n_value_mismatches = 0
    n_source_free_text = 0

    for segment_id in sorted(records):
        obj = records[segment_id]

        missing_for_record = [k for k in sorted(required_top) if k not in obj]
        missing_for_record += [k for k in required_not_null if k in obj and obj[k] is None]
        location = obj.get("location")
        if isinstance(location, dict):
            missing_for_record += [f"location.{k}" for k in required_location if k not in location]
        elif "location" in obj:
            missing_for_record.append("location")
        if missing_for_record:
            n_missing_required += 1
            _add_example(missing_required_examples, {"segment_id": segment_id, "missing": missing_for_record[:20]})

        # The YouTube link must be the watch URL of the record's own video.
        expected_url = f"https://www.youtube.com/watch?v={obj.get('video_id')}"
        if obj.get("youtube_url") != expected_url:
            n_bad_governance_values += 1
            _add_example(bad_value_examples, {"segment_id": segment_id, "field": "youtube_url",
                                              "jsonl": obj.get("youtube_url"), "expected": expected_url})

        metadata = obj.get("metadata")
        if isinstance(metadata, dict):
            leaked = sorted(k for k in metadata if str(k).lower() in free_text_keys)
            if leaked:
                n_source_free_text += 1
                _add_example(source_free_text_examples, {"segment_id": segment_id, "keys": leaked})

        exp = expected.get(segment_id)
        if exp is None:
            continue
        if obj.get("video_id") != exp["video_id"]:
            n_value_mismatches += 1
            _add_example(mismatch_examples, {"segment_id": segment_id, "field": "video_id",
                                             "jsonl": obj.get("video_id"), "expected": exp["video_id"]})
        for fld in ("start_time_s", "end_time_s"):
            if not _float_close(obj.get(fld), exp[fld]):
                n_value_mismatches += 1
                _add_example(mismatch_examples, {"segment_id": segment_id, "field": fld, "jsonl": obj.get(fld),
                                                 "expected": exp[fld]})

    report.add(
        "crowd_index_jsonl.required_schema_fields",
        ok=(n_missing_required == 0),
        details={"records_with_missing_required_fields": n_missing_required, "examples": missing_required_examples},
        warn=False,
    )
    report.add(
        "crowd_index_jsonl.values_match_mapping",
        ok=(n_value_mismatches == 0),
        details={"mismatch_count": n_value_mismatches, "examples": mismatch_examples},
        warn=False,
    )
    report.add(
        "crowd_index_jsonl.youtube_url_matches_video_id",
        ok=(n_bad_governance_values == 0),
        details={"bad_value_count": n_bad_governance_values, "examples": bad_value_examples},
        warn=False,
    )
    report.add(
        "crowd_index_jsonl.no_source_free_text_metadata",
        ok=(n_source_free_text == 0),
        details={"records_with_source_free_text_keys": n_source_free_text, "examples": source_free_text_examples},
        warn=(n_source_free_text > 0),
    )

    total_duration_jsonl = 0.0
    for obj in records.values():
        try:
            dur = _jsonl_processed_duration_seconds(float(obj.get("start_time_s")), float(obj.get("end_time_s")))
            total_duration_jsonl += float(dur or 0.0)
        except (TypeError, ValueError):
            pass
    total_duration_expected = sum(float(v.get("processed_duration_s") or 0.0) for v in expected.values())
    unique_uploads_jsonl = len({str(obj.get("video_id")) for obj in records.values() if obj.get("video_id")})
    unique_uploads_expected = len({str(v.get("video_id")) for v in expected.values() if v.get("video_id")})

    report.add(
        "crowd_index_jsonl.summary_totals_match_mapping",
        ok=(
            unique_uploads_jsonl == unique_uploads_expected
            and _float_close(total_duration_jsonl, total_duration_expected, tol=1e-4)
        ),
        details={
            "jsonl_unique_uploads": unique_uploads_jsonl,
            "expected_unique_uploads": unique_uploads_expected,
            "jsonl_total_processed_duration_s": round(total_duration_jsonl, 6),
            "expected_total_processed_duration_s": round(total_duration_expected, 6),
            "jsonl_total_processed_duration_h": round(total_duration_jsonl / 3600.0, 2),
            "expected_total_processed_duration_h": round(total_duration_expected / 3600.0, 2),
        },
        warn=False,
    )

    summary = {
        "jsonl": read_summary,
        "expected_records_from_mapping": len(expected),
        "missing_record_count": len(missing_ids),
        "extra_record_count": len(extra_ids),
        "unique_uploads_jsonl": unique_uploads_jsonl,
        "unique_uploads_expected": unique_uploads_expected,
        "total_processed_duration_s_jsonl": round(total_duration_jsonl, 6),
        "total_processed_duration_s_expected": round(total_duration_expected, 6),
    }
    logger.info("\n=== crowd_index.jsonl validation ===")
    logger.info(json.dumps(summary, indent=2))
    return summary


