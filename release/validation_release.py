def _setup_logger(out_dir: Path) -> logging.Logger:
    """Logger to the console and to out_dir/validate_release.log."""
    out_dir.mkdir(parents=True, exist_ok=True)
    logger = logging.getLogger("validate_release")
    logger.setLevel(logging.INFO)
    if logger.handlers:  # already set up (re-run in a notebook)
        return logger

    fmt = logging.Formatter("%(asctime)s - %(levelname)-8s - %(message)s")
    for handler in (logging.StreamHandler(), logging.FileHandler(out_dir / "validate_release.log", encoding="utf-8")):
        handler.setLevel(logging.INFO)
        handler.setFormatter(fmt)
        logger.addHandler(handler)
    return logger


def sha256_file(path: Path, chunk_size: int = 1024 * 1024) -> str:
    """Hex SHA-256 of a file, read in chunks."""
    h = hashlib.sha256()
    with path.open("rb") as f:
        for b in iter(lambda: f.read(chunk_size), b""):
            h.update(b)
    return h.hexdigest()


def count_csv_data_rows(path: Path) -> Optional[int]:
    """Return number of data rows in a CSV (lines minus the header). None if unreadable."""
    try:
        with path.open("r", encoding="utf-8", errors="replace") as f:
            return max(sum(1 for _ in f) - 1, 0)
    except Exception:
        return None


def _read_csv_dicts(path: Path) -> Tuple[List[str], List[Dict[str, Any]]]:
    """(fieldnames, rows as dicts) of a CSV file."""
    with path.open("r", encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        rows = list(reader)
        return list(reader.fieldnames or []), rows


def _num_from_str(s: str) -> Optional[float]:
    """A number written as text, with thousands commas and an optional %; None if not a number."""
    if s is None:
        return None
    ss = str(s).strip().replace(",", "")
    if ss.endswith("%"):
        ss = ss[:-1].strip()
    try:
        return float(ss) if ss else None
    except ValueError:
        return None


def _to_float_maybe(x: Any) -> Optional[float]:
    """x as a finite float, else None."""
    try:
        f = float(x)
    except Exception:
        return None
    return f if math.isfinite(f) else None


def _int_from_any(v: Any) -> Optional[int]:
    """v as an int (floats and numeric text truncated), else None."""
    try:
        return int(v)
    except Exception:
        f = _to_float_maybe(str(v).strip())
        return None if f is None else int(f)


def norm_list_of_lists_int(x: Any) -> List[List[int]]:
    """A nested code cell (time_of_day, vehicle_type) as one list of ints per video; values that are not numbers
    are dropped."""
    out: List[List[int]] = []
    for item in parse_list(x):
        ints = (_int_from_any(t) for t in (item if isinstance(item, list) else [item]))
        out.append([i for i in ints if i is not None])
    return out


def _float_or_raw(x: Any) -> Any:
    """x as a float, or x itself when it is not a number (so the segment checks can report it)."""
    try:
        return float(x)
    except Exception:
        return x


def norm_list_of_lists_float(x: Any) -> List[List[Any]]:
    """A nested time cell (start_time, end_time) as one list of floats per video; values that are not numbers are
    kept as they are."""
    return [[_float_or_raw(t) for t in (item if isinstance(item, list) else [item])] for item in parse_list(x)]


def fmt_int(n: int) -> str:
    return f"{n:,}"


def fmt_float(x: float, nd: int = 2) -> str:
    return f"{x:,.{nd}f}"


@dataclass
class Check:
    name: str
    ok: bool
    severity: str  # PASS/WARN/FAIL
    details: Dict[str, Any]


class Report:
    """The list of checks written to validate_release_report.json."""

    def __init__(self) -> None:
        self.checks: List[Check] = []

    def add(self, name: str, ok: bool, details: Optional[Dict[str, Any]] = None, warn: bool = False) -> None:
        """Add a check: PASS if ok, else WARN when warn is set, else FAIL."""
        severity = "PASS" if ok else ("WARN" if warn else "FAIL")
        self.checks.append(Check(name=name, ok=ok, severity=severity, details=details or {}))

    def summary(self) -> Dict[str, int]:
        c = Counter(ch.severity for ch in self.checks)
        return {"pass": c["PASS"], "warn": c["WARN"], "fail": c["FAIL"]}

    def to_dict(self) -> Dict[str, Any]:
        return {
            "summary": self.summary(),
            "checks": [
                {"name": ch.name, "ok": ch.ok, "severity": ch.severity, "details": ch.details} for ch in self.checks
            ],
        }


